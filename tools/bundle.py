#!/usr/bin/env python3
"""Concatenate the project's .ts files (in pxt.json order) into dist/main.ts,
so the whole game can be pasted into the MakeCode web editor's JavaScript view.

Usage:  python3 tools/bundle.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    with open(os.path.join(ROOT, "pxt.json"), encoding="utf-8") as f:
        files = json.load(f)["files"]

    parts = ["// GENERATED by tools/bundle.py - do not edit, edit the source files.\n"]
    for name in files:
        if not name.endswith(".ts"):
            continue
        with open(os.path.join(ROOT, name), encoding="utf-8") as f:
            src = f.read().rstrip() + "\n"
        bar = "// " + "=" * 74
        parts.append("\n%s\n// %s\n%s\n\n%s" % (bar, name, bar, src))

    out_dir = os.path.join(ROOT, "dist")
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, "main.ts")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("".join(parts))
    print("wrote %s (%d files)" % (os.path.relpath(out_path, ROOT), len(files)))


if __name__ == "__main__":
    main()
